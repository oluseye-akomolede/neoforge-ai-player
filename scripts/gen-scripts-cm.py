#!/usr/bin/env python3
"""Regenerate deploy/agent-scripts.yaml from agent/scripts/*.js.

The ConfigMap duplicates the script text, so the two can drift. This script is
the single direction of truth: the .js files are authoritative, the ConfigMap is
output. Run it after any script edit and commit both.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPTS = os.path.join(ROOT, "agent", "scripts")
OUT = os.path.join(ROOT, "deploy", "agent-scripts.yaml")

HEADER = """# The M2 scripts, delivered to the agent pods as files.
#
# scout.js is the first script (task 8.2). It lives here rather than baked into
# the image so a script change does not need a rebuild -- but that only holds if
# the pod actually MOUNTS this, which the step-4 TEST plan does.
#
# `bindings` is the bot-to-script map, and it is the ONLY switch that turns
# script mode on for a bot: {"Scout": "scout.js"}. It replaced a `"script":
# "<path>"` key in the bot's profile, for a reason worth keeping recorded -- the
# profiles directory is an emptyDir seeded from the image, so a profile edit
# survived only until the next pod restart, and the plan's "rollback restores
# that file" story was false the moment anything restarted the pod. Bindings
# live in the ConfigMap, so they survive restarts and the rollback is deleting
# the entry.
#
# No bindings entry means no script: a bot absent from this map runs the
# planner exactly as before, which is the safe default for all five bots.
#
# Everything below is GENERATED by scripts/gen-scripts-cm.py from
# agent/scripts/. Edit the .js or bindings.json, then regenerate; do not
# hand-edit the generated blocks.
"""


def main():
    blocks = []
    # bindings.json first: it is the switch, and an operator scanning the
    # ConfigMap should see what is wired before the script bodies.
    bindings_path = os.path.join(SCRIPTS, "bindings.json")
    if os.path.exists(bindings_path):
        text = open(bindings_path, encoding="utf-8").read()
        body = "\n".join(("    " + ln) if ln else "" for ln in text.rstrip("\n").split("\n"))
        blocks.append(f"  bindings.json: |\n{body}")
    for name in sorted(os.listdir(SCRIPTS)):
        if not name.endswith(".js"):
            continue
        text = open(os.path.join(SCRIPTS, name), encoding="utf-8").read()
        body = "\n".join(("    " + ln) if ln else "" for ln in text.rstrip("\n").split("\n"))
        blocks.append(f"  {name}: |\n{body}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(HEADER + "\napiVersion: v1\nkind: ConfigMap\nmetadata:\n"
                "  name: agent-scripts\n  labels:\n    app: aibot-agent\n"
                "data:\n" + "\n".join(blocks) + "\n")


if __name__ == "__main__":
    main()
